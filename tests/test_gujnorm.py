@pytest.mark.parametrize("n,w", [(0, "શૂન્ય"), (45, "પિસ્તાળીસ"), (99, "નવ્વાણું"), (100, "એકસો"), (110, "એકસો દસ"),
                                 (1001, "એક હજાર એક"), (125000, "એક લાખ પચીસ હજાર"),
                                 (34567890, "ત્રણ કરોડ પિસ્તાળીસ લાખ સડસઠ હજાર આઠસો નેવું")])
def test_num_words(n, w):
    assert num_words(n) == w


def test_year_words():
    assert year_words(1947) == "ઓગણીસો સુડતાળીસ"
    assert year_words(1800) == "અઢારસો"
    assert year_words(2026) == "બે હજાર છવ્વીસ"


def test_every_clock_time_is_words():
    for h in range(24):
        for m in range(60):
            w = time_words(h, m)
            assert w and not any(c.isdigit() for c in w), (h, m, w)


def test_no_digits_survive_on_testset():
    from testset import ITEMS
    import re
    for it in ITEMS:
        out = normalize(it["text"])
        stray = [tok for tok in re.findall(r"\S*\d\S*", out) if not re.search(r"[A-Za-z]", tok)]
        assert not stray, (it["text"], out)


def test_idempotent():
    for raw, _ in CASES:
        once = normalize(raw)
        assert normalize(once) == once
